FontAtlas& FontAtlas::Get()
{
    static FontAtlas s_Instance;
    return s_Instance;
}

bool FontAtlas::Initialize()
{
    if (m_Ready) return true;
    BuildBuiltinAtlas();
    m_Ready = true;
    return true;
}

bool FontAtlas::LoadTTF(const std::string& path, float32 pixelHeight)
{
    TTFLoader loader;
    if (!loader.LoadFromFile(path))
    {
        GOOD_LOG_ERROR("FontAtlas", "Failed to load TTF: '{}'", path);
        return false;
    }

    // Растеризуем в 2x размере для чёткости, потом масштабируем при рендере
    float32 rasterSize = pixelHeight * 2.0f;

    std::vector<byte> pixels;
    int32 atlasW, atlasH;
    if (!loader.RasterizeAtlas(rasterSize, pixels, atlasW, atlasH))
    {
        GOOD_LOG_ERROR("FontAtlas", "Failed to rasterize TTF");
        return false;
    }

    if (m_TextureID) { glDeleteTextures(1, &m_TextureID); m_TextureID = 0; }

    glGenTextures(1, &m_TextureID);
    glBindTexture(GL_TEXTURE_2D, m_TextureID);

    // NEAREST для чёткости пиксельных шрифтов
    // LINEAR для сглаженных TTF
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, atlasW, atlasH, 0,
                 GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
    glBindTexture(GL_TEXTURE_2D, 0);

    for (int32 ch = 32; ch <= 126; ++ch)
    {
        const auto& src = loader.GetChar(static_cast<char>(ch));
        m_Chars[ch].u0       = src.u0;
        m_Chars[ch].v0       = src.v0;
        m_Chars[ch].u1       = src.u1;
        m_Chars[ch].v1       = src.v1;
        m_Chars[ch].width    = src.width;
        m_Chars[ch].height   = src.height;
        m_Chars[ch].xOffset  = src.xOffset;
        m_Chars[ch].yOffset  = src.yOffset;
        m_Chars[ch].advanceX = src.advanceX;
    }

    m_PixelHeight = rasterSize;
    m_HasTTF      = true;
    m_Ready       = true;

    GOOD_LOG_INFO("FontAtlas", "TTF loaded: '{}' (raster {}px, display {}px) atlas={}x{}",
        path, static_cast<int32>(rasterSize), static_cast<int32>(pixelHeight),
        atlasW, atlasH);
    return true;
}

void FontAtlas::Shutdown()
{
    if (m_TextureID) { glDeleteTextures(1, &m_TextureID); m_TextureID = 0; }
    m_Ready  = false;
    m_HasTTF = false;
}

void FontAtlas::BuildBuiltinAtlas()
{
    std::vector<uint8> pixels(ATLAS_W * ATLAS_H * 4, 0);

    for (int32 ci = 0; ci < 95; ++ci)
    {
        int32 col = ci % COLS;
        int32 row = ci / COLS;

        for (int32 y = 0; y < CHAR_H; ++y)
        {
            uint8 bits = s_BuiltinGlyphs[ci][y];
            for (int32 x = 0; x < CHAR_W; ++x)
            {
                if (bits & (1 << x))
                {
                    int32 px = col * CHAR_W + x;
                    int32 py = row * CHAR_H + y;
                    int32 idx = (py * ATLAS_W + px) * 4;
                    pixels[idx] = pixels[idx+1] = pixels[idx+2] = 255;
                    pixels[idx+3] = 255;
                }
            }
        }

        // UV для встроенного шрифта
        int32 ch = ci + 32;
        if (ch < 128)
        {
            m_Chars[ch].u0 = static_cast<float32>(col * CHAR_W) / ATLAS_W;
            m_Chars[ch].v0 = static_cast<float32>(row * CHAR_H) / ATLAS_H;
            m_Chars[ch].u1 = static_cast<float32>((col+1) * CHAR_W) / ATLAS_W;
            m_Chars[ch].v1 = static_cast<float32>((row+1) * CHAR_H) / ATLAS_H;
            m_Chars[ch].width    = CHAR_W;
            m_Chars[ch].height   = CHAR_H;
            m_Chars[ch].advanceX = CHAR_W + 1;
        }
    }

    glGenTextures(1, &m_TextureID);
    glBindTexture(GL_TEXTURE_2D, m_TextureID);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, ATLAS_W, ATLAS_H, 0,
                 GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
    glBindTexture(GL_TEXTURE_2D, 0);

    m_PixelHeight = 8.0f;
    GOOD_LOG_INFO("FontAtlas", "Builtin font atlas created {}x{}", ATLAS_W, ATLAS_H);
}

void FontAtlas::GetCharUV(char c, float32& u0, float32& v0,
                           float32& u1, float32& v1) const
{
    int32 idx = static_cast<int32>(c);
    if (idx >= 32 && idx < 128)
    {
        u0 = m_Chars[idx].u0;
        v0 = m_Chars[idx].v0;
        u1 = m_Chars[idx].u1;
        v1 = m_Chars[idx].v1;
    }
    else
    {
        u0 = v0 = u1 = v1 = 0.0f;
    }
}

const FontCharInfo& FontAtlas::GetCharInfo(char c) const
{
    int32 idx = static_cast<int32>(c);
    if (idx >= 0 && idx < 128) return m_Chars[idx];
    static FontCharInfo s_Empty;
    return s_Empty;
}

